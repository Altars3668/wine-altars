int main( int argc, char **argv )
{
    IMultiLanguage2 *mlang;
    IMultiLanguage *mlang1;
    MIMECSETINFO info;
    unsigned int i;
    HRESULT hr;
    BSTR name;

    CoInitialize( NULL );
    if (CoCreateInstance( &CLSID_CMultiLanguage, NULL, CLSCTX_INPROC_SERVER, &IID_IMultiLanguage2, (void **)&mlang )) return 1;
    for (i = 0; i < ARRAY_SIZE(names); i++)
    {
        memset( &info, 0, sizeof(info) );
        name = SysAllocString( names[i] );
        if (argc > 1)
        {
            IMultiLanguage2_QueryInterface( mlang, &IID_IMultiLanguage, (void **)&mlang1 );
            hr = IMultiLanguage_GetCharsetInfo( mlang1, name, &info );
            IMultiLanguage_Release( mlang1 );
        }
        else hr = IMultiLanguage2_GetCharsetInfo( mlang, name, &info );
        SysFreeString( name );
        if (hr) printf( "%ls %#lx\n", names[i], hr );
        else printf( "%ls %u %u %ls\n", names[i], info.uiCodePage, info.uiInternetEncoding, info.wszCharset );
    }
    IMultiLanguage2_Release( mlang );
    return 0;
}
